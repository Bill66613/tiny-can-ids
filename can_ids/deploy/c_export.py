def export_model_to_c(
    model: Any,
    model_type: str,
    output_dir: str | Path,
    model_name: str = "tiny_ids",
    bits: int = 8,
) -> tuple[Path, Path]:
    """Export any supported model to C header + inference source code.

    Dispatches to the appropriate export functions based on *model_type*.
    Each model type gets a distinct filename suffix.

    Args:
        model: A fitted model (TinyNeuralNetwork, LogisticRegression, or
            DecisionTreeClassifier).
        model_type: One of ``"tnn"``, ``"lr"``, or ``"dt"``.
        output_dir: Directory for output files.
        model_name: Base name prefix for C identifiers and filenames.
        bits: Quantization bit-width (for TNN and LR).

    Returns:
        Tuple ``(header_path, source_path)``.

    Raises:
        ValueError: If *model_type* is not recognised.
    """
    from can_ids.models.compress import (
        ModelQuantizer,
        quantize_logistic_regression,
        export_decision_tree_structure,
    )

    output_dir = Path(output_dir)

    if model_type == "tnn":
        quantizer = ModelQuantizer(model=model, bits=bits)
        quantizer.quantize()
        name = f"{model_name}_tnn"
        header = export_weights_to_c_header(
            quantizer, output_dir / f"{name}_weights", model_name=name
        )
        source = generate_inference_c_code(
            quantizer, output_dir / f"{name}_inference", model_name=name
        )
    elif model_type == "lr":
        qlr = quantize_logistic_regression(model, bits=bits)
        name = f"{model_name}_lr"
        header = export_lr_to_c_header(qlr, output_dir / f"{name}_weights", model_name=name)
        source = generate_lr_inference_c_code(
            qlr, output_dir / f"{name}_inference", model_name=name
        )
    elif model_type == "dt":
        edt = export_decision_tree_structure(model)
        name = f"{model_name}_dt"
        header = export_dt_to_c_header(edt, output_dir / f"{name}_weights", model_name=name)
        source = generate_dt_inference_c_code(
            edt, output_dir / f"{name}_inference", model_name=name
        )
    else:
        raise ValueError(
            f"Unknown model_type '{model_type}'. Use 'tnn', 'lr', or 'dt'."
        )

    return header, source

def export_dos_tnn_weights_to_c_header(
    quantizer: Any,
    path: str | Path,
    model_name: str = "tiny_ids",
    window_size: int = 50,   
    n_features: int = 12,    
) -> Path:
    """Write quantized model weights as a C header file.

    The header defines one ``static const int8_t`` array per layer
    (kernel and bias), together with scale factors and dimension macros.

    Args:
        quantizer: A :class:`~can_ids.models.compress.ModelQuantizer` that
            has already been :meth:`~can_ids.models.compress.ModelQuantizer.quantize`\\ d.
        path: Output file path.  ``.h`` extension is added if absent.
        model_name: Prefix used for all generated C identifiers.

    Returns:
        The resolved :class:`~pathlib.Path` of the written header.
    """
    path = Path(path)
    if path.suffix != ".h":
        path = path.with_suffix(".h")
    path.parent.mkdir(parents=True, exist_ok=True)

    guard = f"{model_name.upper()}_WEIGHTS_H"
    lines: list[str] = [
        f"/* Auto-generated by tiny-can-ids – do not edit. */",
        f"#ifndef {guard}",
        f"#define {guard}",
        "",
        "#include <stdint.h>",
        "/* --- Model Metadata --- */",                               
        f"#define {model_name.upper()}_WINDOW_SIZE {window_size}",    
        f"#define {model_name.upper()}_N_FEATURES {n_features}",
        "",
        "/* --- Data Structures --- */",
        "#ifndef CAN_FRAME_T_DEFINED",            
        "#define CAN_FRAME_T_DEFINED",
        "typedef struct {",
        "    double timestamp;",
        "    uint32_t id;",
        "    uint8_t dlc;",
        "    uint8_t data[8];",
        "} CAN_Frame_t;",
        "#endif",
        "",
        "/* --- Public APIs --- */",
        f"void {model_name}_process_window(const CAN_Frame_t *window, int *result);",
        "",
    ]

    for layer in quantizer.quantized_layers:
        layer_id = _sanitize(layer.name)

        # Kernel
        k = layer.kernel_q.ravel().astype(np.int8)
        lines += _array_block(
            f"{model_name}_{layer_id}_kernel",
            k,
            f"/* scale = {layer.kernel_scale:.8f} */",
        )
        lines += _scale_define(
            f"{model_name.upper()}_{layer_id.upper()}_KERNEL_SCALE",
            layer.kernel_scale,
        )
        lines += _shape_defines(
            f"{model_name.upper()}_{layer_id.upper()}_KERNEL",
            layer.kernel_q.shape,
        )
        lines.append("")

        # Bias
        b = layer.bias_q.ravel().astype(np.int8)
        lines += _array_block(
            f"{model_name}_{layer_id}_bias",
            b,
            f"/* scale = {layer.bias_scale:.8f} */",
        )
        lines += _scale_define(
            f"{model_name.upper()}_{layer_id.upper()}_BIAS_SCALE",
            layer.bias_scale,
        )
        lines.append("")

    lines += [f"#endif /* {guard} */", ""]
    path.write_text("\n".join(lines), encoding="utf-8")
    logger.info("Wrote C weights header to %s", path)
    return path

def generate_dos_tnn_inference_c_code(
    quantizer: Any,
    path: str | Path,
    model_name: str = "tiny_ids",
) -> Path:
    """Generate a C source file with a fully-inlined inference function.

    The generated ``ids_predict(const float *features, int n_features)``
    function implements forward-pass inference for the quantized
    :class:`~can_ids.models.compress.TinyNeuralNetwork` using only integer
    arithmetic and a lookup-table sigmoid approximation.

    Args:
        quantizer: Fitted :class:`~can_ids.models.compress.ModelQuantizer`.
        path: Output file path.  ``.c`` extension is added if absent.
        model_name: Prefix for generated C identifiers.

    Returns:
        The resolved :class:`~pathlib.Path` of the written C source file.
    """
    path = Path(path)
    if path.suffix != ".c":
        path = path.with_suffix(".c")
    path.parent.mkdir(parents=True, exist_ok=True)

    header_name = f"{model_name}_weights.h"
    n_layers = len(quantizer.quantized_layers)

    code_parts: list[str] = [
        f"/* Auto-generated by tiny-can-ids – do not edit. */",
        f'#include "{header_name}"',
        f'#include "{model_name}_scaler.h"',
        "#include <stdint.h>",
        "#include <string.h>",
        "#include <math.h>",
        "",
        "/* Sigmoid approximation: 1 / (1 + exp(-x)) */",
        "static float _sigmoid(float x) {",
        "    return 1.0f / (1.0f + expf(-x));",
        "}",
        "",
        "/* ReLU */",
        "static float _relu(float x) { return x > 0.0f ? x : 0.0f; }",
        "",
    ]

    # Feature Extract (12 Features) 
    code_parts.extend([
        "/* --- Feature Extraction API --- */",
        f"static void {model_name}_feature_extract(const CAN_Frame_t *window, float *out_features) {{",
        "    double sum_dt = 0.0, sum_sq_dt = 0.0, sum_cube_dt = 0.0;",
        "    float min_dt = 1e9f, max_dt = -1.0f;",
        "    int id_counts[2048] = {0};",
        "    int high_priority_count = 0;",
        "    int min_id = 2048, max_id = -1, unique_ids = 0;",
        "    int payload_changes = 0;",
        "    uint64_t total_bits = 0;",
        "",
        f"    for (int i = 0; i < {model_name.upper()}_WINDOW_SIZE; ++i) {{",
        "        /* 1. Timing & Payload Change Stats */",
        "        if (i > 0) {",
        "            float dt = (float)(window[i].timestamp - window[i-1].timestamp);",
        "            sum_dt += dt;",
        "            sum_sq_dt += (double)dt * dt;",
        "            sum_cube_dt += (double)dt * dt * dt;",
        "",
        "            if (dt < min_dt) min_dt = dt;",
        "            if (dt > max_dt) max_dt = dt;",
        "",
        "            int changed = 0;",
        "            for(int b = 0; b < 8; b++) {",
        "                if(window[i].data[b] != window[i-1].data[b]) {",
        "                    changed = 1;",
        "                    break;",
        "                }",
        "            }",
        "            if(changed) payload_changes++;",
        "        }",
        "",
        "        /* 2. ID Stats */",
        "        if (window[i].id < 256) high_priority_count++;",
        "",
        "        int id = window[i].id & 0x7FF;",
        "        if (id_counts[id] == 0) unique_ids++;",
        "        id_counts[id]++;",
        "",
        "        if (id < min_id) min_id = id;",
        "        if (id > max_id) max_id = id;",
        "",
        "        /* 3. Payload Bits (Hamming Weight) */",
        "        for (int b = 0; b < 8; b++) {",
        "            uint8_t byte = window[i].data[b];",
        "            while (byte) {",
        "                byte &= (byte - 1);",
        "                total_bits++;",
        "            }",
        "        }",
        "    }",
        "",
        "    /* --- Final 12 Features Calculation --- */",
        f"    float n = (float){model_name.upper()}_WINDOW_SIZE;",
        "    float n_minus_1 = n - 1.0f;",
        "",
        "    float mean_dt = sum_dt / n_minus_1;",
        "    float variance_dt = (sum_sq_dt / n_minus_1) - (mean_dt * mean_dt);",
        "    if (variance_dt < 0.0f) variance_dt = 0.0f;",
        "    float std_dt = sqrtf(variance_dt);",
        "",
        "    out_features[0] = mean_dt;",
        "    out_features[1] = std_dt;",
        "    out_features[2] = min_dt;",
        "    out_features[3] = max_dt;",
        "    out_features[4] = (sum_dt > 1e-6f) ? (n / (float)sum_dt) : 0.0f; /* Msg Rate */",
        "",
        "    float max_freq = 0.0f, entropy = 0.0f;",
        "    for (int k = 0; k < 2048; k++) {",
        "        if (id_counts[k] > 0) {",
        "            float p = (float)id_counts[k] / n;",
        "            if (p > max_freq) max_freq = p;",
        "            entropy -= p * log2f(p + 1e-12f);",
        "        }",
        "    }",
        "",
        "    out_features[5] = max_freq;",
        "    out_features[6] = entropy;",
        "    out_features[7] = (mean_dt > 1e-12f) ? (std_dt / mean_dt) : 0.0f;",
        "    out_features[8] = (float)total_bits / n;",
        "    out_features[9] = (float)payload_changes / n_minus_1;",
        "    out_features[10] = (float)unique_ids / n;",
        "",
        "    if (std_dt > 1e-6f) {",
        "        out_features[11] = ((sum_cube_dt / n_minus_1) - 3.0f * mean_dt * variance_dt - mean_dt * mean_dt * mean_dt) / (std_dt * std_dt * std_dt);",
        "    } else {",
        "        out_features[11] = 0.0f;",
        "    }",
        "}",
        ""
    ])

    # Emit the forward pass function
    code_parts.append(f"/* --- Predict API --- */")
    code_parts.append(f"static void {model_name}_predict(const float *input, int n_input, int *result) {{")

    prev_size = None
    buffer_decls: list[str] = []
    for idx, layer in enumerate(quantizer.quantized_layers):
        layer_id = _sanitize(layer.name)
        out_size = layer.kernel_q.shape[1]
        buf_name = f"buf{idx}"
        buffer_decls.append(f"    float {buf_name}[{out_size}];")
        in_size = layer.kernel_q.shape[0]
        prev_size = out_size

    code_parts.extend(buffer_decls)
    code_parts.append("")

    prev_buf = "input"
    prev_in = "n_input"
    for idx, layer in enumerate(quantizer.quantized_layers):
        layer_id = _sanitize(layer.name)
        out_size = layer.kernel_q.shape[1]
        in_size = layer.kernel_q.shape[0]
        buf_name = f"buf{idx}"
        is_last = idx == n_layers - 1
        last_layer_outputs = quantizer.quantized_layers[-1].kernel_q.shape[1]
        if is_last and last_layer_outputs > 1:
            # Multi-class: skip activation; argmax is softmax-invariant
            activation = None
        elif is_last:
            activation = "_sigmoid"
        else:
            activation = "_relu"

        code_parts.append(f"    /* Layer: {layer.name} */")
        code_parts.append(f"    for (int j = 0; j < {out_size}; ++j) {{")
        code_parts.append(f"        float acc = {model_name}_{layer_id}_bias[j]")
        code_parts.append(
            f"                    * {model_name.upper()}_{layer_id.upper()}_BIAS_SCALE;"
        )
        code_parts.append(f"        for (int i = 0; i < {in_size}; ++i) {{")
        code_parts.append(f"            acc += {prev_buf}[i]")
        code_parts.append(
            f"                  * (float){model_name}_{layer_id}_kernel[i * {out_size} + j]"
        )
        code_parts.append(
            f"                  * {model_name.upper()}_{layer_id.upper()}_KERNEL_SCALE;"
        )
        code_parts.append(f"        }}")
        if activation is not None:
            code_parts.append(f"        {buf_name}[j] = {activation}(acc);")
        else:
            code_parts.append(f"        {buf_name}[j] = acc;")
        code_parts.append(f"    }}")
        code_parts.append("")

        prev_buf = buf_name

    # Final output: decision from last buffer
    last_layer = quantizer.quantized_layers[-1]
    n_outputs = last_layer.kernel_q.shape[1]
    if n_outputs == 1:
        code_parts.append(f"    *result = {prev_buf}[0] >= 0.75f ? 1 : 0;")
    else:
        # Multi-class classification: argmax
        code_parts.append(f"    int best_class = 0;")
        code_parts.append(f"    float best_score = {prev_buf}[0];")
        code_parts.append(f"    for (int c = 1; c < {n_outputs}; ++c) {{")
        code_parts.append(f"        if ({prev_buf}[c] > best_score) {{")
        code_parts.append(f"            best_score = {prev_buf}[c];")
        code_parts.append(f"            best_class = c;")
        code_parts.append(f"        }}")
        code_parts.append(f"    }}")
        code_parts.append(f"    *result = best_class;")
    code_parts.append("}")
    code_parts.append("")

    # High-level API
    code_parts.extend([
        "/* ========================================================",
        " * HIGH-LEVEL API (All-in-one)",
        " * ======================================================== */",
        f"void {model_name}_process_window(const CAN_Frame_t *window, int *result) {{",
        f"    float features_buffer[{model_name.upper()}_N_FEATURES];",
        "",
        f"    {model_name}_feature_extract(window, features_buffer);",
        "",
        f"    for(int i = 0; i < {model_name.upper()}_N_FEATURES; i++) {{",
        f"        features_buffer[i] = (features_buffer[i] - {model_name}_scaler_mean[i]) / {model_name}_scaler_scale[i];",
        "    }",
        "",
        f"    {model_name}_predict(features_buffer, {model_name.upper()}_N_FEATURES, result);",
        "}",
        ""
    ])

    path.write_text("\n".join(code_parts), encoding="utf-8")
    logger.info("Wrote C inference code to %s", path)
    return path

def export_dos_dt_to_c_header(
    exported_dt: Any,
    path: str | Path,
    model_name: str = "tiny_ids_dt",
    window_size: int = 50,
    n_features: int = 8,
) -> Path:
    """Write decision tree structure as a C header file.

    Stores the tree as parallel arrays (feature index, threshold, children,
    leaf class) for a compact while-loop traversal on the MCU.

    Args:
        exported_dt: An :class:`~can_ids.models.compress.ExportedDecisionTree`.
        path: Output file path.  ``.h`` extension is added if absent.
        model_name: Prefix used for all generated C identifiers.

    Returns:
        The resolved :class:`~pathlib.Path` of the written header.
    """
    path = Path(path)
    if path.suffix != ".h":
        path = path.with_suffix(".h")
    path.parent.mkdir(parents=True, exist_ok=True)

    guard = f"{model_name.upper()}_WEIGHTS_H"
    n = exported_dt.n_nodes
    lines: list[str] = [
        f"/* Auto-generated by tiny-can-ids – do not edit. */",
        f"#ifndef {guard}",
        f"#define {guard}",
        "",
        "#include <stdint.h>",
        "",
        "/* --- Model Metadata --- */",
        f"#define {model_name.upper()}_WINDOW_SIZE {window_size}",
        f"#define {model_name.upper()}_N_FEATURES {n_features}",
        f"#define {model_name.upper()}_SAMPLING_RATE_MS 1", 
        "",
        "/* --- Model Structure --- */",
        f"#define {model_name.upper()}_N_NODES {n}",
        f"#define {model_name.upper()}_N_CLASSES {exported_dt.n_classes}",
        f"#define {model_name.upper()}_MAX_DEPTH {exported_dt.max_depth}",
        "",
        "/* --- Data Structures --- */",
        "#ifndef CAN_FRAME_T_DEFINED",            
        "#define CAN_FRAME_T_DEFINED",
        "typedef struct {",
        "    double timestamp;",
        "    uint32_t id;",
        "    uint8_t dlc;",
        "    uint8_t data[8];",
        "} CAN_Frame_t;",
        "#endif",
        "",
        "/* --- Public APIs --- */",
        f"void {model_name}_process_window(const CAN_Frame_t *window, int *result);",
        "",
    ]

    # Feature index per node
    lines += _array_block(
        f"{model_name}_feature_index",
        exported_dt.feature_index.ravel().astype(np.int8),
        "/* Feature index to split on (-1 = leaf) */",
    )
    lines.append("")

    # Threshold per node (float)
    threshold_vals = ", ".join(f"{v:.8f}f" for v in exported_dt.threshold)
    wrapped = textwrap.fill(threshold_vals, width=72, subsequent_indent="    ")
    lines += [
        "/* Split threshold per node */",
        f"static const float {model_name}_threshold[{n}] = {{",
        f"    {wrapped}",
        "};",
        "",
    ]

    # Children left
    lines += _array_block(
        f"{model_name}_children_left",
        exported_dt.children_left.ravel().astype(np.int8),
        "/* Left child index (-1 = leaf) */",
    )
    lines.append("")

    # Children right
    lines += _array_block(
        f"{model_name}_children_right",
        exported_dt.children_right.ravel().astype(np.int8),
        "/* Right child index (-1 = leaf) */",
    )
    lines.append("")

    # Leaf class
    lines += _array_block(
        f"{model_name}_leaf_class",
        exported_dt.leaf_class.ravel().astype(np.int8),
        "/* Predicted class at leaf (-1 = internal node) */",
    )
    lines.append("")

    lines += [f"#endif /* {guard} */", ""]
    path.write_text("\n".join(lines), encoding="utf-8")
    logger.info("Wrote DT C weights header to %s", path)
    return path

def generate_dos_dt_inference_c_code(
    exported_dt: Any,
    path: str | Path,
    model_name: str = "tiny_ids_dt",
) -> Path:
    """Generate C inference code for a decision tree.

    The generated function traverses the tree using a simple while-loop
    over the parallel arrays.  Uses only a single float comparison per
    node – extremely efficient for MCU deployment.

    Args:
        exported_dt: An :class:`~can_ids.models.compress.ExportedDecisionTree`.
        path: Output file path.  ``.c`` extension is added if absent.
        model_name: Prefix for generated C identifiers.

    Returns:
        The resolved :class:`~pathlib.Path` of the written C source file.
    """
    path = Path(path)
    if path.suffix != ".c":
        path = path.with_suffix(".c")
    path.parent.mkdir(parents=True, exist_ok=True)

    header_name = f"{model_name}_weights.h"
    code: list[str] = [
        f"/* Auto-generated by tiny-can-ids – do not edit. */",
        f'#include "{header_name}"',
        "#include <stdint.h>",
        "#include <math.h>",
        "",
        f"static void {model_name}_feature_extract(const CAN_Frame_t *window, float *out_features) {{",
        "    double sum_dt = 0, sum_sq_dt = 0;",
        "    float min_dt = 1e9f;",
        "    int id_counts[2048] = {0};",
        "    int high_priority_count = 0;",
        "    int max_consecutive = 1, current_consecutive = 1;",
        "",
        f"    for (int i = 0; i < {model_name.upper()}_WINDOW_SIZE; ++i) {{",
        "        if (i > 0) {",
        "            float dt = (float)(window[i].timestamp - window[i-1].timestamp);",
        "            sum_dt += dt;",
        "            sum_sq_dt += dt * dt;",
        "            if (dt < min_dt) min_dt = dt;",
        "        }",
        "        if (window[i].id < 256) high_priority_count++;",
        "        id_counts[window[i].id & 0x7FF]++;",
        "",
        "        if (i > 0) {",
        "            if (window[i].id == window[i-1].id) {",
        "                current_consecutive++;",
        "            } else {",
        "                if (current_consecutive > max_consecutive) max_consecutive = current_consecutive;",
        "                current_consecutive = 1;",
        "            }",
        "        }",
        "    }",
        "",
        "    if (current_consecutive > max_consecutive) max_consecutive = current_consecutive;",
        "",
        f"    float avg_dt = sum_dt / ({model_name.upper()}_WINDOW_SIZE - 1);",
        f"    out_features[0] = avg_dt;",
        f"    out_features[1] = sqrtf((sum_sq_dt / ({model_name.upper()}_WINDOW_SIZE - 1)) - (avg_dt * avg_dt));",
        f"    out_features[2] = (sum_dt > 1e-6f) ? ({model_name.upper()}_WINDOW_SIZE / (float)sum_dt) : 0.0f;",
        "",
        "    float max_freq = 0, entropy = 0;",
        "    for (int k = 0; k < 2048; ++k) {",
        "        if (id_counts[k] > 0) {",
        f"            float p = (float)id_counts[k] / {model_name.upper()}_WINDOW_SIZE;",
        "            if (p > max_freq) max_freq = p;",
        "            entropy -= p * log2f(p + 1e-12f);",
        "        }",
        "    }",
        "    out_features[3] = max_freq;",
        "    out_features[4] = entropy;",
        "    out_features[5] = min_dt;",
        f"    out_features[6] = (float)high_priority_count / {model_name.upper()}_WINDOW_SIZE;",
        "    out_features[7] = (float)max_consecutive;",
        "}",
        "",
        "/* --- Predict API --- */",
        f"static void {model_name}_predict(const float *input, int n_input, int *result) {{",
        f"    int node = 0;",
        f"    while ({model_name}_children_left[node] != -1) {{",
        f"        if (input[{model_name}_feature_index[node]] <= {model_name}_threshold[node])",
        f"            node = {model_name}_children_left[node];",
        f"        else",
        f"            node = {model_name}_children_right[node];",
        f"    }}",
        f"    *result = {model_name}_leaf_class[node];",
        "}",
        "",
        "/* ========================================================",
        " * HIGH-LEVEL API (All-in-one)",
        " * ======================================================== */",
        f"void {model_name}_process_window(const CAN_Frame_t *window, int *result) {{",
        f"    float features_buffer[{model_name.upper()}_N_FEATURES];",
        f"    {model_name}_feature_extract(window, features_buffer);",
        f"    {model_name}_predict(features_buffer, {model_name.upper()}_N_FEATURES, result);",
        "}",
        "",
    ]

    path.write_text("\n".join(code), encoding="utf-8")
    logger.info("Wrote DT C inference code to %s", path)
    return path

def export_dos_model_to_c(
    model: Any,
    model_type: str,
    output_dir: str | Path,
    model_name: str = "tiny_ids",
    bits: int = 8,
    window_size: int = 50,
    n_features: int = 12,
    scaler: Any = None,
) -> tuple[Path, Path]:
    """Export any supported model to C header + inference source code.

    Dispatches to the appropriate export functions based on *model_type*.
    Each model type gets a distinct filename suffix.

    Args:
        model: A fitted model (TinyNeuralNetwork, LogisticRegression, or
            DecisionTreeClassifier).
        model_type: One of ``"tnn"``, ``"lr"``, or ``"dt"``.
        output_dir: Directory for output files.
        model_name: Base name prefix for C identifiers and filenames.
        bits: Quantization bit-width (for TNN and LR).

    Returns:
        Tuple ``(header_path, source_path)``.

    Raises:
        ValueError: If *model_type* is not recognised.
    """
    from can_ids.models.compress import (
        ModelQuantizer,
        quantize_logistic_regression,
        export_decision_tree_structure,
    )

    output_dir = Path(output_dir)

    if model_type == "tnn":
        quantizer = ModelQuantizer(model=model, bits=bits)
        quantizer.quantize()
        name = f"{model_name}_tnn"
        header = export_dos_tnn_weights_to_c_header(
            quantizer, output_dir / f"{name}_weights", model_name=name, window_size=window_size, n_features=n_features
        )
        source = generate_dos_tnn_inference_c_code(
            quantizer, output_dir / f"{name}_inference", model_name=name
        )
        if scaler is not None:
            export_scaler_to_c_header(
                scaler, 
                output_dir / f"{model_name}_tnn_scaler", 
                model_name=f"{model_name}_tnn"
            )
    elif model_type == "lr":
        qlr = quantize_logistic_regression(model, bits=bits)
        name = f"{model_name}_lr"
        header = export_lr_to_c_header(qlr, output_dir / f"{name}_weights", model_name=name)
        source = generate_lr_inference_c_code(
            qlr, output_dir / f"{name}_inference", model_name=name
        )
    elif model_type == "dt":
        edt = export_decision_tree_structure(model)
        name = f"{model_name}_dt"
        header = export_dos_dt_to_c_header(edt, output_dir / f"{name}_weights", model_name=name, window_size=window_size, n_features=n_features)
        source = generate_dos_dt_inference_c_code(
            edt, output_dir / f"{name}_inference", model_name=name
        )
    else:
        raise ValueError(
            f"Unknown model_type '{model_type}'. Use 'tnn', 'lr', or 'dt'."
        )

    return header, source

