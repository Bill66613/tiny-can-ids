def _sanitize(name: str) -> str:
    """Replace non-alphanumeric characters with underscores."""
    return "".join(c if c.isalnum() else "_" for c in name)


def _array_block(var_name: str, data: np.ndarray, comment: str = "") -> list[str]:
    """Format a C static array initialiser."""
    vals = ", ".join(str(int(v)) for v in data)
    wrapped = textwrap.fill(vals, width=72, subsequent_indent="    ")
    lines = []
    if comment:
        lines.append(comment)
    lines.append(f"static const int8_t {var_name}[{data.size}] = {{")
    lines.append(f"    {wrapped}")
    lines.append("};")
    return lines


def _scale_define(macro: str, scale: float) -> list[str]:
    return [f"#define {macro} {scale:.8f}f"]


def _shape_defines(prefix: str, shape: tuple[int, ...]) -> list[str]:
    lines = []
    for dim_idx, dim_val in enumerate(shape):
        lines.append(f"#define {prefix}_DIM{dim_idx} {dim_val}")
    return lines

def export_scaler_to_c_header(
    scaler: Any,
    path: str | Path,
    model_name: str = "dos_ids_tnn",
) -> Path:
    """Automatically generate a C header file containing StandardScaler coefficients."""
    path = Path(path)
    if path.suffix != ".h":
        path = path.with_suffix(".h")
    path.parent.mkdir(parents=True, exist_ok=True)

    guard = f"{model_name.upper()}_SCALER_H"
    
    # Get the mean and scale values ​​from the StandardScaler object and cast them to C's float format.
    mean_vals = ", ".join([f"{x:.8f}f" for x in scaler.mean_])
    scale_vals = ", ".join([f"{x:.8f}f" for x in scaler.scale_])
    
    lines = [
        f"/* Auto-generated Scaler Data - Do not edit */",
        f"#ifndef {guard}",
        f"#define {guard}",
        "",
        f"static const float {model_name}_scaler_mean[12] = {{ {mean_vals} }};",
        f"static const float {model_name}_scaler_scale[12] = {{ {scale_vals} }};",
        "",
        f"#endif /* {guard} */"
    ]
    
    path.write_text("\n".join(lines), encoding="utf-8")
    return path
