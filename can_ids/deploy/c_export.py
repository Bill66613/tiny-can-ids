def export_lr_to_c_header(
    quantized_lr: Any,
    path: str | Path,
    model_name: str = "tiny_ids_lr",
) -> Path:
    """Write quantized logistic regression weights as a C header file.

    Args:
        quantized_lr: A :class:`~can_ids.models.compress.QuantizedLR`.
        path: Output file path.  ``.h`` extension is added if absent.
        model_name: Prefix used for all generated C identifiers.

    Returns:
        The resolved :class:`~pathlib.Path` of the written header.
    """
    path = Path(path)
    if path.suffix != ".h":
        path = path.with_suffix(".h")
    path.parent.mkdir(parents=True, exist_ok=True)

    guard = f"{model_name.upper()}_WEIGHTS_H"
    lines: list[str] = [
        f"/* Auto-generated by tiny-can-ids – do not edit. */",
        f"#ifndef {guard}",
        f"#define {guard}",
        "",
        "#include <stdint.h>",
        "",
        f"#define {model_name.upper()}_N_FEATURES {quantized_lr.n_features}",
        f"#define {model_name.upper()}_N_CLASSES {quantized_lr.n_classes}",
        "",
    ]

    # Coefficient matrix (row-major: n_rows x n_features)
    coef = quantized_lr.coef_q.ravel().astype(np.int8)
    lines += _array_block(f"{model_name}_coef", coef, "/* Coefficient matrix */")
    lines += _scale_define(f"{model_name.upper()}_COEF_SCALE", quantized_lr.coef_scale)
    lines.append("")

    # Intercept
    intercept = quantized_lr.intercept_q.ravel().astype(np.int8)
    lines += _array_block(f"{model_name}_intercept", intercept, "/* Intercept */")
    lines += _scale_define(
        f"{model_name.upper()}_INTERCEPT_SCALE", quantized_lr.intercept_scale
    )
    lines.append("")

    lines += [f"#endif /* {guard} */", ""]
    path.write_text("\n".join(lines), encoding="utf-8")
    logger.info("Wrote LR C weights header to %s", path)
    return path


def generate_lr_inference_c_code(
    quantized_lr: Any,
    path: str | Path,
    model_name: str = "tiny_ids_lr",
) -> Path:
    """Generate C inference code for a quantized logistic regression.

    The generated function computes a simple dot product of input features
    with quantized coefficients, adds the intercept, and returns:

    * Binary: ``sigmoid(z) >= 0.5 ? 1 : 0``
    * Multi-class: ``argmax(z)`` (softmax-invariant)

    Args:
        quantized_lr: A :class:`~can_ids.models.compress.QuantizedLR`.
        path: Output file path.  ``.c`` extension is added if absent.
        model_name: Prefix for generated C identifiers.

    Returns:
        The resolved :class:`~pathlib.Path` of the written C source file.
    """
    path = Path(path)
    if path.suffix != ".c":
        path = path.with_suffix(".c")
    path.parent.mkdir(parents=True, exist_ok=True)

    header_name = f"{model_name}_weights.h"
    n_features = quantized_lr.n_features
    # Binary LR in sklearn: coef_ is (1, n_features)
    is_binary = quantized_lr.coef_q.shape[0] == 1

    code: list[str] = [
        f"/* Auto-generated by tiny-can-ids – do not edit. */",
        f'#include "{header_name}"',
        "#include <stdint.h>",
        "#include <math.h>",
        "",
        "/* Sigmoid: 1 / (1 + exp(-x)) */",
        "static float _sigmoid(float x) {",
        "    return 1.0f / (1.0f + expf(-x));",
        "}",
        "",
        f"int {model_name}_predict(const float *input, int n_input) {{",
    ]

    if is_binary:
        code += [
            f"    float z = (float){model_name}_intercept[0]",
            f"              * {model_name.upper()}_INTERCEPT_SCALE;",
            f"    for (int i = 0; i < {n_features}; ++i) {{",
            f"        z += input[i]",
            f"             * (float){model_name}_coef[i]",
            f"             * {model_name.upper()}_COEF_SCALE;",
            f"    }}",
            f"    return _sigmoid(z) >= 0.5f ? 1 : 0;",
        ]
    else:
        n_rows = quantized_lr.coef_q.shape[0]
        code += [
            f"    int best_class = 0;",
            f"    float best_score = -1e30f;",
            f"    for (int c = 0; c < {n_rows}; ++c) {{",
            f"        float z = (float){model_name}_intercept[c]",
            f"                  * {model_name.upper()}_INTERCEPT_SCALE;",
            f"        for (int i = 0; i < {n_features}; ++i) {{",
            f"            z += input[i]",
            f"                 * (float){model_name}_coef[c * {n_features} + i]",
            f"                 * {model_name.upper()}_COEF_SCALE;",
            f"        }}",
            f"        if (z > best_score) {{",
            f"            best_score = z;",
            f"            best_class = c;",
            f"        }}",
            f"    }}",
            f"    return best_class;",
        ]

    code += ["}", ""]
    path.write_text("\n".join(code), encoding="utf-8")
    logger.info("Wrote LR C inference code to %s", path)
    return path


